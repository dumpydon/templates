#==================================================================================
# 1️⃣ BASIC DEFINITIONS
#==================================================================================
# nums = [a0, a1, a2, ..., a(n-1)]

# RIGHT ROTATE by k:
# move last k elements → front

# LEFT ROTATE by k:
# move first k elements → end


#==================================================================================
# 2️⃣ DIRECT FORMULAS (MOST IMPORTANT 🔥)
#==================================================================================

#--------------------------------------------------
# RIGHT ROTATE
#--------------------------------------------------
# Example: [1,2,3,4,5], k=2 → [4,5,1,2,3]
def right_rotate(nums, k):
    n = len(nums)
    k %= n
    return nums[-k:] + nums[:-k]


#--------------------------------------------------
# LEFT ROTATE
#--------------------------------------------------
# Example: [1,2,3,4,5], k=2 → [3,4,5,1,2]
def left_rotate(nums, k):
    n = len(nums)
    k %= n
    return nums[k:] + nums[:k]


#==================================================================================
# 3️⃣ INDEX MAPPING (VERY IMPORTANT 🔥)
#==================================================================================

# Suppose original index = i

#--------------------------------------------------
# RIGHT ROTATE by k
#--------------------------------------------------
# new_index = (i + k) % n
# OR:
# element at new index j came from:
# original_index = (j - k + n) % n


#--------------------------------------------------
# LEFT ROTATE by k
#--------------------------------------------------
# new_index = (i - k) % n
# OR:
# element at new index j came from:
# original_index = (j + k) % n


#==================================================================================
# 4️⃣ LAST ELEMENT AFTER ROTATION
#==================================================================================

#--------------------------------------------------
# RIGHT ROTATE
#--------------------------------------------------
# last element = nums[n - k - 1]

#--------------------------------------------------
# LEFT ROTATE
#--------------------------------------------------
# last element = nums[k - 1]


#==================================================================================
# 5️⃣ VISUAL MEMORY TRICK
#==================================================================================
# RIGHT → take from RIGHT → bring FRONT
# LEFT  → take from LEFT  → send BACK


#==================================================================================
# 6️⃣ HANDLE LARGE k
#==================================================================================
# ALWAYS:
# k = k % n


#==================================================================================
# 7️⃣ REVERSE TRICK (O(1) SPACE) 🔥🔥
#==================================================================================

#--------------------------------------------------
# RIGHT ROTATE by k
#--------------------------------------------------
def right_rotate_inplace(nums, k):
    n = len(nums)
    k %= n

    nums.reverse()           # reverse whole
    nums[:k] = reversed(nums[:k])   # reverse first k
    nums[k:] = reversed(nums[k:])   # reverse rest


#--------------------------------------------------
# LEFT ROTATE by k
#--------------------------------------------------
def left_rotate_inplace(nums, k):
    n = len(nums)
    k %= n

    nums.reverse()                # reverse whole
    nums[n-k:] = reversed(nums[n-k:])  # reverse last k
    nums[:n-k] = reversed(nums[:n-k])  # reverse rest


#==================================================================================
# 8️⃣ ROTATION CHECK (STRING PATTERN)
#==================================================================================

def is_rotation(s, goal):
    return len(s) == len(goal) and goal in (s + s)


#==================================================================================
# 9️⃣ SORTED + ROTATED CHECK
#==================================================================================

def is_sorted_rotated(nums):
    n = len(nums)
    count = 0

    for i in range(n):
        if nums[i] > nums[(i+1) % n]:
            count += 1

    return count <= 1


